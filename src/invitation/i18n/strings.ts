export function makeTranslator(locale: string, overrides: Record<string, Record<string, string>> = {}, voice?: Voice) {
  const voiced = voice ? EVENT_VOICES[voice] : undefined;
  return (key: StringKey, vars?: Record<string, string | number>): string => {
    // an owner's own wording always wins; the occasion's voice only replaces the built-in English
    const raw = overrides[locale]?.[key] ?? (locale === "en" ? voiced?.[key] : undefined) ?? BUILT_IN[locale]?.[key] ?? overrides.en?.[key] ?? voiced?.[key] ?? EN[key] ?? key;
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  };
}
