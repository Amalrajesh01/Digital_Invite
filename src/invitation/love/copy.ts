export type LoveKey = Exclude<keyof typeof EN, "headline">;

/** A translator for a gift. `locale` is the gift's default language; anything other than Malayalam uses English labels. */
export function loveText(locale: string) {
  const table = (locale === "ml" ? ML : EN) as Record<string, string | Record<LoveOccasion, string>>;
  const fill = (s: string, vars?: Record<string, string | number>) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : s);
  return {
    t: (key: LoveKey, vars?: Record<string, string | number>) => fill(String(table[key] ?? EN[key]), vars),
    headline: (o: LoveOccasion, name: string) => fill((table.headline as Record<LoveOccasion, string>)[o] ?? EN.headline[o], { name }),
  };
}
