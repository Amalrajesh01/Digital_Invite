export type FlText = ReturnType<typeof flText>;

export function flText(locale: string) {
  const table: Record<string, string> = locale === "ml" ? ML : EN;
  return (key: FlKey, vars?: Record<string, string | number>) => {
    const s = table[key] ?? EN[key];
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : s;
  };
}
