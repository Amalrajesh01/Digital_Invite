/**
 * Writes docs/TEMPLATES.md — the specification of every template — from the code that defines them, so the document can
 * never drift from what ships. Each entry carries the seventeen things a design is judged on: id, name, occasion,
 * concept, customer, style, palette, typography, hero, layout, imagery, movement, interactions, mobile behaviour,
 * languages, package compatibility and accessibility.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { OPENING_LABELS } from "../src/domain/doc/constants";
import { SECTION_META } from "../src/domain/doc/sections";
import { ALL_DIRECTIONS, DIRECTIONS } from "../src/domain/design/directions";
import { CINEMATIC_SPECS } from "../src/domain/design/template-specs-cinematic";
import { CASTING } from "../src/domain/imagery/casting";
import { libraryTrack } from "../src/domain/music/library";
import { TEMPLATE_SPECS, specSections, specsFor } from "../src/domain/design/template-specs";
import { THEME_SEEDS } from "../src/domain/design/themes";
import { CATEGORIES } from "../src/domain/catalogue/categories";
import { LOVE_SPECS } from "../src/domain/love/templates";
import { LOVE_EXPERIENCE_INFO, MOOD_LABEL, MOOD_THEME } from "../src/domain/love/constants";
import { PACKAGE_KEYS, defaultFeaturesFor } from "../src/domain/packages/features";

const heroLabel = (v: string) => SECTION_META.hero.variants.find((x) => x.key === v)?.label ?? v;
const swatch = (slug: string) => {
  const t = THEME_SEEDS.find((x) => x.slug === slug)!;
  const c = t.tokens.colors;
  return { name: t.name, text: `${t.name} — paper ${c.background}, ink ${c.text}, main ${c.primary}, accent ${c.accent}, night ${c.inverse}`, type: `${t.tokens.fonts.heading} for names and headings, ${t.tokens.fonts.body} for reading text${t.tokens.fonts.script !== t.tokens.fonts.heading ? `, ${t.tokens.fonts.script} for flourishes` : ""}` };
};
const essential = new Set<string>(defaultFeaturesFor("ESSENTIAL"));
void PACKAGE_KEYS;

let md = `# Template specifications\n\n_Generated by \`npm run docs:templates\` from \`src/domain/design/template-specs.ts\` and \`src/domain/love/templates.ts\`. Do not edit by hand._\n\n`;
md += `Every occasion offers **five designs that differ in the ways a guest can see** — how the invitation opens, how it begins, how the story is ordered, which colours and typefaces it uses, and how it moves. \`tests/template-catalogue.test.ts\` fails the build if two designs of one occasion share an opening, a hero, a visual direction, a colour theme or the same beginning.\n\n`;
md += `## The visual directions\n\n| Direction | What it means | Typography | Movement | Mobile | Accessibility |\n|---|---|---|---|---|---|\n`;
for (const k of ALL_DIRECTIONS) { const d = DIRECTIONS[k]; md += `| **${d.label}** | ${d.promise} | ${d.typography} | ${d.animation} | ${d.mobile} | ${d.accessibility} |\n`; }
md += `\nPackage compatibility is the same for every design: all three packages can use all of them. The package decides which *pages* appear (see [FEATURES.md](FEATURES.md)); for example Essential omits guest management, the wishes wall and the live-day pages, which every design includes from Signature and Luxury upwards. Language: each invitation is written in one language, in whatever language the customer writes it.\n\n`;

md += `## The cinematic wedding set — differentiation matrix

Twenty-five weddings, each with its own opening scene, hero composition, direction, palette and pace. Two of them never share an opening *and* a hero; every opening photograph is different. The full specification of each follows under *Wedding*.

`;
md += `| # | Template | Opening | Hero | Direction | Motion | Palette | Tone |
|---|---|---|---|---|---|---|---|
`;
CINEMATIC_SPECS.forEach((s, i) => { md += `| ${String(i + 1).padStart(2, "0")} | **${s.name}** (\`${s.slug}\`) | ${OPENING_LABELS[s.opening]} | ${heroLabel(s.hero)} | ${DIRECTIONS[s.direction].label} | ${s.profile} | ${swatch(s.theme).name} | ${s.tone} |
`; });
md += `
`;

const groups = CATEGORIES.filter((c) => specsFor(c.slug).length);
for (const c of groups) {
  md += `## ${c.name}\n\n`;
  for (const s of specsFor(c.slug)) {
    const sw = swatch(s.theme);
    const labels = [...new Set(specSections(s).filter((x) => x.enabled && SECTION_META[x.type].phases.includes("PUBLISHED")).map((x) => SECTION_META[x.type].label))];
    const gated = specSections(s).filter((x) => SECTION_META[x.type].feature && !essential.has(SECTION_META[x.type].feature!)).length;
    md += `### ${s.name}${s.edition ? " (tradition edition)" : ""}\n\n`;
    md += `| | |\n|---|---|\n`;
    md += `| **Template ID** | \`${s.slug}\` |\n| **Occasion** | ${c.name} (starts as: ${s.eventType.replace(/_/g, " ")}) |\n| **Creative concept** | ${s.concept} |\n| **Target customer** | ${s.target.join("; ")} |\n`;
    md += `| **Visual style** | ${DIRECTIONS[s.direction].label} |\n| **Colour palette** | ${sw.text} |\n| **Typography** | ${sw.type} |\n`;
    md += `| **Opening** | ${OPENING_LABELS[s.opening]} |\n| **Hero composition** | ${heroLabel(s.hero)} |\n| **Section layout** | ${labels.join(" → ")} |\n`;
    md += `| **Image strategy** | ${s.images} |\n| **Animation strategy** | ${s.motion} |\n| **Interactive features** | ${s.interactions.join("; ")} |\n`;
    if (s.tone) md += `| **Emotional tone** | ${s.tone} |
`;
    if (s.story) md += `| **Storytelling structure** | ${s.story} |
`;
    if (s.gallery) md += `| **Gallery treatment** | ${s.gallery} |
`;
    if (s.transition) md += `| **Transition style** | ${s.transition} |
`;
    if (s.profile) md += `| **Motion profile** | ${s.profile[0].toUpperCase()}${s.profile.slice(1)} |
`;
    if (s.music?.length) md += `| **Music recommendations** | ${s.music.map((id) => libraryTrack(id)?.title ?? id).join("; ")} (first is the default) |
`;
    if (s.tags?.length) md += `| **Library filters** | ${s.tags.join(", ")} |
`;
    if (CASTING[s.slug]) md += `| **Opening photograph** | ${CASTING[s.slug].heroBrief} |
`;
    md += `| **Mobile behaviour** | ${s.mobile ?? DIRECTIONS[s.direction].mobile} |\n| **Languages** | One language per invitation: the customer's own words, in any language |\n`;
    md += `| **Package compatibility** | All packages (${gated} pages need Signature or Luxury) |\n| **Accessibility** | ${DIRECTIONS[s.direction].accessibility} |\n| **Sample content** | \`${s.demo}\` |\n\n`;
  }
}

md += `## For My Love — five experiences\n\nThese are not five colourings of one page. Each opens differently, moves differently and asks something different of the person who receives it. The mood the sender chooses (${Object.values(MOOD_LABEL).join(", ")}) only changes the colours.\n\n`;
for (const s of LOVE_SPECS) {
  const sw = swatch(MOOD_THEME[s.moods[0]]);
  md += `### ${s.name}\n\n| | |\n|---|---|\n`;
  md += `| **Template ID** | \`${s.slug}\` |\n| **Occasion** | For My Love |\n| **Creative concept** | ${s.concept} |\n| **Target customer** | ${s.target.join("; ")} |\n| **Visual style** | ${MOOD_LABEL[s.moods[0]]} mood (also: ${s.moods.slice(1).map((m) => MOOD_LABEL[m]).join(", ")}) |\n`;
  md += `| **Colour palette** | ${sw.text} |\n| **Typography** | ${sw.type} |\n| **Opening** | Its own: ${LOVE_EXPERIENCE_INFO[s.experience].howItFeels} |\n| **Image strategy** | ${s.images} |\n| **Animation strategy** | ${s.motion} |\n`;
  md += `| **Interactive features** | ${s.interactions.join("; ")} |\n| **What the recipient is asked to do** | ${s.recipient} |\n| **Mobile behaviour** | Designed phone-first; single column; large tap targets |\n| **Languages** | English and Malayalam labels in full; the sender's words in any language |\n`;
  md += `| **Package compatibility** | Sold separately from the three invitation packages; uses no package entitlement beyond Essential |\n| **Accessibility** | Every playful step has a plain button and a skip; nothing is timed; reduced motion switches all effects off |\n| **Sample content** | \`${s.demo}\` |\n\n`;
}

mkdirSync("docs", { recursive: true });
writeFileSync("docs/TEMPLATES.md", md);
console.log(`docs/TEMPLATES.md — ${TEMPLATE_SPECS.length} designs and ${LOVE_SPECS.length} love experiences`);
