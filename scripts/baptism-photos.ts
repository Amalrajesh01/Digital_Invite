import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { PHOTOS, ROLES } from "../src/domain/baptism/photos";
import { STORY } from "../src/domain/baptism/story";
import { BAPTISM_SPECS } from "../src/domain/design/template-specs-baptism";

/**
 * npm run baptism:photos — writes docs/BAPTISM-PHOTOS.md (every demonstration photograph of the baptism templates: what it shows, who made
 * it, under what licence, where it is used) and the Wikimedia Commons block of assets/stock/CREDITS.md. Run it after changing `photos.ts`.
 */
const name = (slug: string) => BAPTISM_SPECS.find((s) => s.slug === slug)?.name ?? slug;
const usage = new Map<string, string[]>();
const note = (id: string | undefined, where: string) => { if (id) usage.set(id, [...(usage.get(id) ?? []), where]); };
for (const [slug, st] of Object.entries(STORY)) {
  const n = name(slug);
  note(st.hero, `${n} (opening)`);
  note(st.story, `${n} (our little story)`);
  for (const [id] of st.gallery) note(id, `${n} (gallery)`);
  note(st.people?.parents, `${n} (parents)`);
  note(st.people?.grandparents, `${n} (grandparents)`);
  note(st.church, `${n} (church)`);
}

async function main() {
const rows = Object.entries(PHOTOS).sort(([, a], [, b]) => ROLES.indexOf(a.role) - ROLES.indexOf(b.role) || a.mood.localeCompare(b.mood));
const link = (id: string, page?: string) => (page ? `[\`${id}\`](${page})` : `\`${id}\``);
const md = `# The baptism photographs

Generated by \`npm run baptism:photos\` from \`src/domain/baptism/photos.ts\` — do not edit by hand.

Every picture below is a **licensed stand-in**: it makes a sample invitation look finished before a family has uploaded anything, and the studio marks it as the sample’s (“Still the sample”) until the family replaces it. They are real photographs of real people who are not the fictional families in the samples, exactly as for every other stock photograph (see [assets/stock/CREDITS.md](../assets/stock/CREDITS.md)). Nothing is hot-linked: the files are in \`assets/stock/\` and go through the normal media pipeline.

* **Selection** was by relevance (a baby, a baptism, hands, feet, a parent or grandparent holding a baby), photographic quality, licence and how well the light sits in a template’s palette. It was **not** by skin tone or appearance of the people shown, and nobody’s face has been altered.
* **Licences used:** CC0 / Unsplash License (no attribution required, given anyway), CC BY and CC BY-SA (credit required — it is in CREDITS.md; **the resized copy of a CC BY-SA picture stays under the same licence**).
* **Left out on purpose:** photographs of recognisable public figures (including royal baptisms), museum catalogue photographs, anything with a wedding, and pictures of a naked infant.
* **Weak spots, honestly:** there are few good photographs of *grandparents* holding a baby under an open licence, and none at all of godparents, so those sections show a monogram unless a family adds a picture. The only baptism-in-progress photograph is one water-pouring close-up.

${rows.length} photographs · ${Object.keys(STORY).length} templates · [the gate](../src/domain/baptism/check.ts): \`npm run baptism:check\`

| Photograph | Shows | Role · light | Credit | Licence | Used in |
|---|---|---|---|---|---|
${rows.map(([id, p]) => `| ${link(id, p.page)} | ${p.alt} | ${p.role} · ${p.mood}${p.face ? " · face" : ""} | ${p.by} | ${p.licence} | ${(usage.get(id) ?? ["—"]).join("; ")} |`).join("\n")}
`;
await writeFile(path.join(process.cwd(), "docs", "BAPTISM-PHOTOS.md"), md);

// ── CREDITS.md: the Commons pictures need their credit published ─────────────────────────────────
const START = "<!-- baptism-photos:start -->";
const END = "<!-- baptism-photos:end -->";
const commons = rows.filter(([id]) => id.startsWith("wc-"));
const block = `${START}
## Wikimedia Commons photographs for the baptism templates (babies, hands, feet, parents, a baptism)

Fetched with \`scripts/dev/commons.mjs\` (CC0, public domain, CC BY and CC BY-SA only) and described in \`src/domain/baptism/photos.ts\`. The sample invitations of the baptism category use them as stand-ins (see [docs/BAPTISM-PHOTOS.md](../../docs/BAPTISM-PHOTOS.md)). CC BY and CC BY-SA require this credit; **CC BY-SA 4.0/2.0 requires the resized copy to stay under the same licence.** Click the file name for the original, its author and the licence text.

| Photo id | Author | Licence and original |
|---|---|---|
${commons.map(([id, p]) => `| \`${id}\` | ${p.by} | ${p.licence} — ${p.page ? `[${decodeURIComponent(p.page.split("File:")[1] ?? id).replace(/_/g, " ")}](${p.page})` : "—"} |`).join("\n")}
${END}`;
const creditsPath = path.join(process.cwd(), "assets", "stock", "CREDITS.md");
let credits = await readFile(creditsPath, "utf8");
const crlf = credits.includes("\r\n");
credits = credits.replace(/\r\n/g, "\n");
const a = credits.indexOf(START), b = credits.indexOf(END);
credits = a >= 0 && b > a ? credits.slice(0, a) + block + credits.slice(b + END.length) : `${credits.trimEnd()}\n\n${block}\n`;
await writeFile(creditsPath, crlf ? credits.replace(/\n/g, "\r\n") : credits);
console.log(`docs/BAPTISM-PHOTOS.md and assets/stock/CREDITS.md written (${rows.length} photographs, ${commons.length} from Commons)`);
}
main();
