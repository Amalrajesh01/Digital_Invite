import { writeFile } from "node:fs/promises";
import { BAPTISM_SPECS } from "../src/domain/design/template-specs-baptism";
import { BAPTISM_SAMPLES } from "../src/domain/catalogue/baptism-samples";
import { MANIFEST, NEVER, SLOT_FRAME, SLOTS } from "../src/domain/baptism/images";

/** npm run baptism:images — writes docs/BAPTISM-IMAGES.md: the manifest and the prompt for every picture a baptism template could use. */
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const rows = (id: string) => MANIFEST.filter((r) => r.templateId === id);

const out: string[] = [
  "# Baptism templates — image manifest and prompts",
  "",
  "_Generated by `npm run baptism:images` from `src/domain/baptism/images.ts`. Do not edit by hand._",
  "",
  "## What this is",
  "",
  "A baptism invitation is only as good as its pictures, and a wrong picture is worse than none. So every place a photograph can go — twenty",
  "templates × six slots — is written down here with what belongs in it, and **a picture is used only where it is about what the section",
  "says**. Families supply their own photographs; this manifest describes the pictures the *sample* invitations would like, so that they",
  "can show what a finished one looks like.",
  "",
  "**Nothing in this repository can generate an image**, and none has been generated. Until someone makes pictures from the prompts below,",
  "a slot is either a bundled, licensed photograph that genuinely fits (`stand-in`) or empty (`pending`): the sample then shows its drawn",
  "scene, and its family is introduced by name with a monogram. We never borrow a wedding, birthday or unrelated picture to fill a gap,",
  "and we never paint invitation wording, names, dates or scripture into an image.",
  "",
  "## How to add a generated picture",
  "",
  "1. Copy the prompt of the slot, add the standing instruction below, and make the picture with the service of your choice.",
  "2. Look at it: is the subject right, the culture right, the light right, is there any text in it, does it crop well?",
  "3. `npm run baptism:ingest -- <template> <slot> <file> --tool \"<service>\" --alt \"<description>\"` — resizes, cleans, saves, records provenance and (for a hero) makes it the sample’s photograph.",
  "4. `npm run baptism:check`, then re-seed the sample (`npm run demo:drop -- <sample>` then `SEED_ONLY=public-demos npm run db:seed`) and look at it in the template at phone size.",
  "5. The owner approves it (`approved`) — code never does.",
  "",
  `**Standing instruction for every prompt:** ${NEVER}`,
  "",
  "## Slots",
  "",
  "| Slot | Section | Crop | Used for |", "|---|---|---|---|",
  ...SLOTS.map((s) => `| \`${s}\` | ${SLOT_FRAME[s].section} | ${SLOT_FRAME[s].ratio} | ${SLOT_FRAME[s].note} |`),
  "",
  "## Overview",
  "",
  "| # | Template | Sample | Hero | Details |",
  "|---|---|---|---|---|",
  ...BAPTISM_SPECS.map((s, i) => {
    const r = rows(s.slug);
    const h = r.find((x) => x.slot === "hero")!;
    const n = (st: string) => r.filter((x) => x.status === st).length;
    return `| ${String(i + 1).padStart(2, "0")} | [${s.name}](#${s.slug}) | ${BAPTISM_SAMPLES[s.slug].child}, ${BAPTISM_SAMPLES[s.slug].city} | ${h.status === "pending" ? "drawn scene only" : `${h.status}: \`${h.stock}\``} | ${n("stand-in")} stand-in · ${n("generated")} generated · ${n("pending")} pending |`;
  }),
  "",
];
for (const s of BAPTISM_SPECS) {
  out.push(`## ${s.name}`, `<a id="${s.slug}"></a>`, "", `*${s.concept}*`, "", "| Slot | Status | Asset id | Picture | Subject · culture | Aspect · focal | Reviewed · approved |", "|---|---|---|---|---|---|---|");
  for (const r of rows(s.slug)) out.push(`| ${r.slot} | ${r.status} | \`${r.assetId}\` | ${r.stock ? `\`${r.stock}\` (${r.source})` : "—"} | ${cell(r.subject)} · ${cell(r.culture)} | ${r.aspect} · ${r.focal.x}/${r.focal.y} | ${r.reviewed ? "yes" : "no"} · ${r.approved ? "yes" : "no"} |`);
  out.push("", "**Prompts**", "");
  for (const r of rows(s.slug)) out.push(`- **${r.slot}** — ${r.prompt}`);
  out.push("");
}
writeFile("docs/BAPTISM-IMAGES.md", `${out.join("\n")}\n`).then(() => console.log(`docs/BAPTISM-IMAGES.md  (${MANIFEST.length} slots)`));
